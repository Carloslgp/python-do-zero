# Exercício 2 — Guardando seu nome
# Aula 01: print(), input() e variáveis
 
# Criamos uma variável chamada "nome" e guardamos uma string dentro dela.
# O sinal de = faz a atribuição: o valor da direita vai para a variável da esquerda.
nome = "Carlos"
 
# A f-string (texto começando com f"...") permite inserir o valor de uma variável
# diretamente dentro da mensagem usando chaves {}.
print(f"Olá, {nome}! Bons estudos.")